CREATE TABLE IF NOT EXISTS hydrogen_station_status (
    status_id BIGSERIAL PRIMARY KEY,
    chrstn_mno VARCHAR(30) NOT NULL REFERENCES hydrogen_stations(chrstn_mno) ON DELETE CASCADE,
    tt_pressr INTEGER,
    prfect_elctc_posbl_alge INTEGER,
    wait_vhcle_alge INTEGER,
    cnf_sttus_cd VARCHAR(10),
    cnf_sttus_nm VARCHAR(50),
    oper_sttus_cd VARCHAR(10),
    oper_sttus_nm VARCHAR(50),
    pos_sttus_cd VARCHAR(10),
    pos_sttus_nm VARCHAR(50),
    last_mdfcn_dt TIMESTAMP,
    created_at TIMESTAMP DEFAULT now(),
    updated_at TIMESTAMP DEFAULT now()
);

CREATE TABLE IF NOT EXISTS hydrogen_station_additional_info (
    additional_info_id BIGSERIAL PRIMARY KEY,
    chrstn_mno VARCHAR(30) NOT NULL REFERENCES hydrogen_stations(chrstn_mno) ON DELETE CASCADE,
    adi_info_se_cd VARCHAR(10),
