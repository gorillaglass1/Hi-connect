    del_at CHAR(1) DEFAULT '0',
    last_mdfcn_dt TIMESTAMP,
    "timestamp" TIMESTAMP,
    created_at TIMESTAMP DEFAULT now(),
    updated_at TIMESTAMP DEFAULT now()
);

